#!/usr/bin/env python3
"""Generate a link-time stub for libGLESv2 with every OpenGL ES 3 entry point.

The webOS toolchain's sysroot ships an OpenGL ES 2 libGLESv2.so, so linking
code that calls ES 3 functions fails. The TV's real driver (ARM Mali) does
export them. This script writes a C file defining every function declared in
the Khronos GLES3/gl3.h as an empty body; it is compiled into a shared library
with the same soname as the real one ("libGLESv2.so") and used only at link
time. It is never packaged: at run time the dynamic loader finds the TV's own
libGLESv2.so.

The stub bodies are never executed. Their C signatures do not matter to the
linker, so each is declared as `void name(void)`.

Usage: gen_gles_stub.py <path/to/GLES3/gl3.h> <output.c>
"""

import re
import sys
from pathlib import Path


def entry_points(header: str) -> list[str]:
    """Names of all functions prototyped with GL_APIENTRY in the header."""
    pattern = re.compile(r"^GL_APICALL\s+.*?GL_APIENTRY\s+(gl\w+)\s*\(", re.MULTILINE)
    return sorted(set(pattern.findall(header)))


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2

    header = Path(sys.argv[1]).read_text(encoding="utf-8")
    names = entry_points(header)
    if len(names) < 200:  # ES 3.0 has ~250 entry points; far fewer means the header changed shape
        print(f"only {len(names)} entry points found in {sys.argv[1]}", file=sys.stderr)
        return 1

    lines = [
        "/* Generated by tools/gen_gles_stub.py. Do not edit.",
        " * Link-time stand-in for the TV's libGLESv2.so (OpenGL ES 3); never shipped. */",
        "",
    ]
    lines += [f"void {name}(void) {{}}" for name in names]
    Path(sys.argv[2]).write_text("\n".join(lines) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
